#!/usr/bin/env node
/**
 * 每日任务：
 *  1. 从 data/backlog.json 放出 N 条新方法到 data/extras.json（默认 2 条）
 *  2. 重新生成 data/extra-methods.js
 *  3. 从 data/pool.json 选当天的 3 条，写入 data/daily.js
 *
 * 同一天重复运行默认幂等；--force 只重算 daily，不会重复放出方法。
 * 用 RELEASE_PER_DAY 环境变量可以调整每天放出的数量。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "data");
const files = {
  pool: path.join(dataDir, "pool.json"),
  extras: path.join(dataDir, "extras.json"),
  backlog: path.join(dataDir, "backlog.json"),
  state: path.join(dataDir, "release-state.json"),
  daily: path.join(dataDir, "daily.js"),
  extraMethods: path.join(dataDir, "extra-methods.js")
};
const force = process.argv.includes("--force");
const releasePerDay = Math.max(1, Number(process.env.RELEASE_PER_DAY || 2));

function readJson(p, fallback) {
  try { return JSON.parse(fs.readFileSync(p, "utf8")); }
  catch (e) { return fallback; }
}
function writeJson(p, value) {
  fs.writeFileSync(p, JSON.stringify(value, null, 2) + "\n", "utf8");
}

let pool = readJson(files.pool, []);
let extras = readJson(files.extras, []);
let backlog = readJson(files.backlog, []);
const releaseState = readJson(files.state, { lastDate: "" });

/* 用上海时区取日期，和页面里的本地日期一致 */
const date = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Shanghai",
  year: "numeric",
  month: "2-digit",
  day: "2-digit"
}).format(new Date());

let releasedNow = [];

/* 1) 每天放出一批新方法（同一天只放一次） */
if (releaseState.lastDate !== date) {
  const take = backlog.slice(0, releasePerDay);
  if (take.length) {
    releasedNow = take.map(x => x.id);
    const released = take.map(x => Object.assign({}, x, { releasedAt: date }));
    extras = extras.concat(released);
    backlog = backlog.slice(take.length);
    for (const m of released) {
      if (!pool.some(p => p.id === m.id)) pool.push({ id: m.id, cat: m.cat });
    }
    writeJson(files.extras, extras);
    writeJson(files.backlog, backlog);
    writeJson(files.pool, pool);
  }
  releaseState.lastDate = date;
  writeJson(files.state, releaseState);
}

/* 2) 保证 pool 里包含所有已经发布的方法 */
let poolChanged = false;
for (const m of extras) {
  if (!pool.some(p => p.id === m.id)) {
    pool.push({ id: m.id, cat: m.cat });
    poolChanged = true;
  }
}
if (poolChanged) writeJson(files.pool, pool);

/* 3) 生成浏览器可用的 extra-methods.js */
const extrasSource = `/* Auto-generated from data/extras.json by scripts/pick-daily.mjs.\n   Do not edit by hand. */\n(function (root, factory) {\n  var methods = factory();\n  if (typeof module !== "undefined" && module.exports) module.exports = methods;\n  else root.EXTRA_METHODS = methods;\n})(typeof globalThis !== "undefined" ? globalThis : this, function () {\n  return ${JSON.stringify(extras, null, 2)};\n});\n`;
fs.writeFileSync(files.extraMethods, extrasSource, "utf8");

/* 同一天已生成过就保持不变（除非 --force） */
if (!force && fs.existsSync(files.daily)) {
  const old = fs.readFileSync(files.daily, "utf8");
  const m = old.match(/"date"\s*:\s*"([^"]+)"/);
  if (m && m[1] === date && releasedNow.length === 0) {
    console.log(`daily.js 已经是 ${date}，跳过（用 --force 强制重算）`);
    process.exit(0);
  }
}

/* 4) 从 pool 里选 3 条：固定种子，同一天结果一致；优先不同维度 */
function xmur3(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return function () {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return (h ^= h >>> 16) >>> 0;
  };
}
function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(xmur3(date)());
const shuffled = [...pool];
for (let i = shuffled.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
}

const picked = [];
const usedCats = new Set();
for (const item of shuffled) {
  if (picked.length >= 3) break;
  if (!usedCats.has(item.cat)) {
    picked.push(item);
    usedCats.add(item.cat);
  }
}
for (const item of shuffled) {
  if (picked.length >= 3) break;
  if (!picked.includes(item)) picked.push(item);
}

const data = { date, ids: picked.map(x => x.id) };
const dailySource = `/* Auto-generated by scripts/pick-daily.mjs at ${new Date().toISOString()}.\n   Do not edit by hand. */\n(function (root) {\n  var data = ${JSON.stringify(data, null, 2)};\n  if (typeof module !== "undefined" && module.exports) module.exports = data;\n  else root.AGENT_DAILY = data;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
fs.writeFileSync(files.daily, dailySource, "utf8");

if (releasedNow.length) {
  console.log(`今日上新 ${releasedNow.length} 条：${releasedNow.join(", ")}（backlog 剩余 ${backlog.length}）`);
} else if (!backlog.length) {
  console.log("backlog 已空，今天只轮换已有方法");
}
console.log(`daily.js -> ${date}: ${picked.map(x => `${x.id}(${x.cat})`).join(", ")}`);
