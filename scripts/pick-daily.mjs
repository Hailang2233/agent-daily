#!/usr/bin/env node
/**
 * 生成当天的「今日 3 条」：data/daily.js
 * 同一天重复运行默认幂等；加 --force 可强制重算。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const poolPath = path.join(root, "data", "pool.json");
const dailyPath = path.join(root, "data", "daily.js");
const force = process.argv.includes("--force");

const pool = JSON.parse(fs.readFileSync(poolPath, "utf8"));
if (!Array.isArray(pool) || pool.length < 3) {
  console.error("data/pool.json 至少需要 3 条方法");
  process.exit(1);
}

/* 用上海时区取日期，和页面里的本地日期一致 */
const date = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Shanghai",
  year: "numeric",
  month: "2-digit",
  day: "2-digit"
}).format(new Date());

/* 同一天已生成过就保持不变 */
if (!force && fs.existsSync(dailyPath)) {
  const old = fs.readFileSync(dailyPath, "utf8");
  const m = old.match(/"date"\s*:\s*"([^"]+)"/);
  if (m && m[1] === date) {
    console.log(`daily.js 已经是 ${date}，跳过（用 --force 强制重算）`);
    process.exit(0);
  }
}

/* 固定种子的伪随机，保证同一天任何机器算出的结果一致 */
function xmur3(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return function () {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return (h ^= h >>> 16) >>> 0;
  };
}
function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(xmur3(date)());
const shuffled = [...pool];
for (let i = shuffled.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
}

/* 优先让三条来自不同维度，不够再补 */
const picked = [];
const usedCats = new Set();
for (const item of shuffled) {
  if (picked.length >= 3) break;
  if (!usedCats.has(item.cat)) {
    picked.push(item);
    usedCats.add(item.cat);
  }
}
for (const item of shuffled) {
  if (picked.length >= 3) break;
  if (!picked.includes(item)) picked.push(item);
}

const data = {
  date,
  ids: picked.map(x => x.id)
};

const content = `/* Auto-generated by scripts/pick-daily.mjs at ${new Date().toISOString()}.\n   Do not edit by hand. */\n(function (root) {\n  var data = ${JSON.stringify(data, null, 2)};\n  if (typeof module !== "undefined" && module.exports) module.exports = data;\n  else root.AGENT_DAILY = data;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;

fs.writeFileSync(dailyPath, content, "utf8");
console.log(`daily.js -> ${date}: ${picked.map(x => `${x.id}(${x.cat})`).join(", ")}`);
