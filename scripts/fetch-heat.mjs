#!/usr/bin/env node
/**
 * 拉取匿名浏览计数，生成 data/heat.js。
 * 默认使用 Abacus（开源、免费、无需账号）；在 data/config.js 里可关闭或换服务。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pool = require(path.join(root, "data", "pool.json"));
const config = require(path.join(root, "data", "config.js"));

const heat = config.heat || {};
const heatPath = path.join(root, "data", "heat.js");
const sleep = ms => new Promise(r => setTimeout(r, ms));

if (!heat.enabled) {
  console.log("heat.enabled = false，跳过热度同步");
  process.exit(0);
}
if (!heat.baseUrl || !heat.namespace) {
  console.error("缺少 heat.baseUrl 或 heat.namespace");
  process.exit(1);
}

const base = String(heat.baseUrl).replace(/\/$/, "");
const ns = encodeURIComponent(heat.namespace);
const counts = {};
let failures = 0;

for (const item of pool) {
  const id = item.id;
  const url = `${base}/get/${ns}/${encodeURIComponent(id)}`;
  let ok = false;
  for (let attempt = 0; attempt < 2 && !ok; attempt++) {
    try {
      const res = await fetch(url, { headers: { "accept": "application/json" } });
      if (res.status === 429) {
        await sleep(5000);
        continue;
      }
      if (!res.ok) throw new Error("HTTP " + res.status);
      const data = await res.json();
      const value = Number(data.value);
      if (Number.isFinite(value) && value > 0) counts[id] = value;
      ok = true;
    } catch (e) {
      if (attempt === 0) await sleep(1500);
    }
  }
  if (!ok) failures++;
  await sleep(400); // 控制在 Abacus 的 30 次 / 10 秒限制内
}

if (failures === pool.length) {
  console.error("全部请求失败，保留现有的 data/heat.js");
  process.exit(0);
}

const content = `/* Auto-generated by scripts/fetch-heat.mjs at ${new Date().toISOString()}.\n   Do not edit by hand. */\n(function (root) {\n  var data = ${JSON.stringify(counts, null, 2)};\n  if (typeof module !== "undefined" && module.exports) module.exports = data;\n  else root.AGENT_HEAT = data;\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;

fs.writeFileSync(heatPath, content, "utf8");
console.log(`heat.js -> ${Object.keys(counts).length} 条有计数，${failures} 条失败`);
